def get_skill_list() -> list[dict]:
    """Return list of skill metadata (without prompts) for display."""
    return [
        {
            "type": k,
            "name": v["name"],
            "description": v["description"],
            "icon": v["icon"],
            "color": v["color"],
        }
        for k, v in SKILLS.items()
    ]


SKILL_ALIASES = {
    "deep-research": "industry",
    "deep_research": "industry",
    "deepResearch": "industry",
    "research": "industry",
}


def normalize_skill_type(skill_type: str) -> str:
    """Return the canonical backend skill type for legacy/frontend aliases."""
    return SKILL_ALIASES.get(skill_type, skill_type)


def get_skill(skill_type: str) -> dict | None:
    """Get full skill definition by type."""
    return SKILLS.get(normalize_skill_type(skill_type))


def get_skill_prompt(skill_type: str) -> str | None:
    """Get the system prompt for a skill."""
    skill = get_skill(skill_type)
    if skill:
        return skill["prompt_template"]
    return None
